def fetch_accuracy():
    """The published holdout figure. Never typed into a page by hand."""
    with urllib.request.urlopen(API + "/backtest-results", timeout=30) as r:
        d = json.loads(r.read().decode("utf-8"))
    wp = d.get("win_probability") or {}
    n = wp.get("total_predictions") or 0
    if n < 100:
        raise SystemExit(
            "Refusing to generate: /backtest-results reports %d predictions. "
            "That is the state that put 0.0%% on the public accuracy page in "
            "August 2026." % n)
    return {"overall": wp.get("overall_accuracy"), "preds": n,
            "matches": d.get("matches_tested")}


def load_venues(min_matches):
    """Only grounds a person would actually search for, merged across duplicate keys.

    A first pass selected purely on match count and it was wrong twice over:

      * Match count does not track searchability. Terdthai Cricket Ground in
        Bangkok has 96 recorded matches and nobody has ever looked it up;
        Edgbaston has 22 and everybody has. Publishing 120 pages selected that
        way produced entries for a German club ground - the exact doorway-page
        pattern Google is right to ignore, and the last thing a site already
        refused by AdSense for "low value content" should ship.
      * The same ground appears under several keys. "Wankhede Stadium" (80
        matches) and "Wankhede Stadium, Mumbai" (64) are one ground; so are the
        two spellings of Gahanga. That would have published two pages for one
        venue with different numbers on each.

    league_data.GROUNDS already solves both - it is hand-curated per league and
    groups every alias of a ground under one display name, which is why it exists
    (see the frontend CLAUDE.md note about "oval" matching Botswana). 56 grounds,
    every one a real venue in a competition this site covers.
    """
    if not os.path.exists(VENUE_JSON):
        raise SystemExit("venue_stats.json not found at %s - this generator "
                         "reads the backend repo beside this one." % VENUE_JSON)
    raw = json.load(open(VENUE_JSON, encoding="utf-8"))

    leagues = {}
    for lg, rows in league_data.GROUNDS.items():
        for display, keys in rows:
            leagues.setdefault(display, {"keys": set(), "leagues": set()})
            leagues[display]["keys"].update(keys)
            leagues[display]["leagues"].add(lg)

    out = []
    for display, meta in leagues.items():
        present = [k for k in meta["keys"] if k in raw]
        if not present:
            continue
        merged = league_data._merge(raw, present)
        if not merged or (merged.get("n") or 0) < min_matches:
            continue
        # _merge returns aggregates only; segments come from the richest key so
        # the phase splits are never averaged across differently-shaped samples.
        best = max(present, key=lambda k: raw[k].get("match_count", 0))
        src = raw[best]
        if not (src.get("segments") or {}).get("inn1"):
            continue
        out.append({
            "key": best,
            "name": display,
            "slug": slugify(display),
            "match_count": merged["n"],
            "avg_first_innings": merged["first"],
            "avg_second_innings": merged["second"],
            "overall_avg_rpo": merged.get("rpo"),
            "segments": src.get("segments"),
            "recent_segments": src.get("recent_segments"),
            "recent_match_count": src.get("recent_match_count"),
            "leagues": sorted(meta["leagues"]),
        })
    out.sort(key=lambda x: -x["match_count"])
    return out


def slugify(name):
    s = re.sub(r"[^a-z0-9]+", "-", (name or "").lower()).strip("-")
    return re.sub(r"-+", "-", s)


# ── reading the numbers ───────────────────────────────────────────────────────

def seg(v, inn, label, key="avg_rpo", recent=False):
    src = (v.get("recent_segments") if recent else v.get("segments")) or {}
    for s in src.get(inn, []):
        if s.get("label") == label:
            return s.get(key)
    return None


def describe(v):
    """Turn one ground's numbers into the sentences that make it its own page."""
    first = v.get("avg_first_innings") or 0
    second = v.get("avg_second_innings") or 0
    gap = round(first - second, 1)

    d1 = seg(v, "inn1", "17-20") or 0
    d2 = seg(v, "inn2", "17-20") or 0
    pp1 = seg(v, "inn1", "1-4") or 0

    # Has the surface drifted? Compare recent death overs with all-time.
    rd1 = seg(v, "inn1", "17-20", recent=True)
    drift = round(rd1 - d1, 2) if rd1 is not None and d1 else None

    if gap >= 15:
        toss = ("a real batting-first advantage - sides batting second average "
                "%.1f runs fewer" % gap)
    elif gap >= 6:
        toss = "a modest edge to batting first, worth about %.0f runs" % gap
    elif gap <= -6:
        toss = ("an edge to CHASING - sides batting second average %.1f runs "
                "more" % abs(gap))
    else:
        toss = ("almost no toss advantage either way - %.1f runs separates the "
                "two innings" % abs(gap))

    if d1 and d2:
        dd = round(d1 - d2, 2)
        if dd >= 1.5:
            death = ("Chases stall here. The last four overs go at %.2f an over "
                     "batting first and only %.2f batting second - a %.2f-run "
                     "collapse in the phase that usually decides a T20."
                     % (d1, d2, dd))
        elif dd <= -1.0:
            death = ("Chases finish strongly here. The last four overs go at "
                     "%.2f an over batting second against %.2f batting first, "
                     "so a target that looks safe often is not." % (d2, d1))
        else:
            death = ("The death overs behave much the same in both innings - "
                     "%.2f an over batting first, %.2f chasing." % (d1, d2))
    else:
        death = ""

    if drift is not None and abs(drift) >= 0.6:
        way = "higher" if drift > 0 else "lower"
        move = ("Recent matches are scoring %s than the all-time record: %.2f "
                "an over at the death against %.2f across the full sample, so "
                "the older figures understate%s what happens now."
                % (way, rd1, d1, "" if drift > 0 else " the difficulty of"))
    elif drift is not None:
        move = ("Recent matches track the long-run record closely, so the "
                "figures below are not being dragged by an old era.")
    else:
        move = ""

    return {"gap": gap, "toss": toss, "death": death, "move": move,
            "first": first, "second": second, "pp1": pp1}


def phase_table(v):
    rows = ""
    for label, name in PHASES:
        r1, w1 = seg(v, "inn1", label), seg(v, "inn1", label, "avg_wickets")
        r2, w2 = seg(v, "inn2", label), seg(v, "inn2", label, "avg_wickets")
        if r1 is None and r2 is None:
            continue
        fmt = lambda x, n=2: "-" if x is None else ("%.*f" % (n, x))
        rows += ('<tr><td>%s <span class="mut">(ov %s)</span></td>'
                 '<td class="n">%s</td><td class="n">%s</td>'
                 '<td class="n">%s</td><td class="n">%s</td></tr>'
                 % (name, label, fmt(r1), fmt(w1, 1), fmt(r2), fmt(w2, 1)))
    return ('<div class="scroll"><table>'
            '<tr><th rowspan="2">Phase</th><th colspan="2" class="n">Batting first</th>'
            '<th colspan="2" class="n">Chasing</th></tr>'
            '<tr><th class="n">Runs/over</th><th class="n">Wickets</th>'
            '<th class="n">Runs/over</th><th class="n">Wickets</th></tr>'
            + rows + "</table></div>")



def par_table(v):
    """A running par score - what the total reads at the end of each phase.

    This is the number a viewer actually wants and no competitor publishes it:
    "is 60 for 2 after 8 overs good HERE". Built by accumulating the measured
    phase run rates rather than dividing a final average into equal chunks,
    which would erase the whole point.
    """
    rows = ""
    for inn, label in (("inn1", "Batting first"), ("inn2", "Chasing")):
        runs = wkts = 0.0
        cells = ""
        ok = False
        for lab, _ in PHASES:
            r = seg(v, inn, lab)
            w = seg(v, inn, lab, "avg_wickets")
            if r is None:
                cells += '<td class="n">-</td>'
                continue
            ok = True
            overs = 4 if lab != "17-20" else 4
            runs += r * overs
            wkts += (w or 0)
            cells += '<td class="n">%d-%d</td>' % (round(runs), round(wkts))
        if ok:
            rows += "<tr><td>%s</td>%s</tr>" % (label, cells)
    if not rows:
        return ""
    heads = "".join('<th class="n">%s ov</th>' % lab.split("-")[1]
                    for lab, _ in PHASES)
    return ('<div class="scroll"><table><tr><th>Par score after</th>%s</tr>%s'
            "</table></div>" % (heads, rows))


def recent_table(v):
    """Recent form against the long-run record, phase by phase."""
    if not (v.get("recent_segments") or {}).get("inn1"):
        return ""
    rows = ""
    for lab, name in PHASES:
        a_ = seg(v, "inn1", lab)
        r_ = seg(v, "inn1", lab, recent=True)
        if a_ is None or r_ is None:
            continue
        d = r_ - a_
        arrow = "&#9650;" if d > 0.25 else ("&#9660;" if d < -0.25 else "&ndash;")
        rows += ('<tr><td>%s <span class="mut">(ov %s)</span></td>'
                 '<td class="n">%.2f</td><td class="n">%.2f</td>'
                 '<td class="n">%s %+.2f</td></tr>'
                 % (name, lab, a_, r_, arrow, d))
    if not rows:
        return ""
    n = v.get("recent_match_count") or 0
    return ('<div class="scroll"><table>'
            '<tr><th>Phase</th><th class="n">All-time</th>'
            '<th class="n">Last %d</th><th class="n">Change</th></tr>%s'
            "</table></div>" % (n, rows))


def volatility(v):
    """How predictable this ground is - the part a probability model cares about."""
    stds = [seg(v, "inn1", lab, "std_rpo") for lab, _ in PHASES]
    stds = [x for x in stds if x]
    if not stds:
        return ""
    avg = sum(stds) / len(stds)
    death = seg(v, "inn1", "17-20", "std_rpo")
    if avg >= 2.9:
        verdict = ("a volatile ground - over-to-over scoring swings widely, so a "
                   "required rate here is less reliable than the same rate elsewhere")
    elif avg <= 2.2:
        verdict = ("a predictable ground - scoring holds close to its average from "
                   "over to over, so a required rate here means what it says")
    else:
        verdict = "about as predictable as a typical T20 ground"
    d = (" The death overs are the loosest part at %.2f." % death) if death else ""
    return ("<p>Measured over-to-over variation averages %.2f runs, which makes this "
            "%s.%s</p>" % (avg, verdict, d))


