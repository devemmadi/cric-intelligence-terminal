def patch_vercel(routes, dry):
    cfg = json.load(open(VERCEL, encoding="utf-8"))
    rw = [r for r in cfg.get("rewrites", []) if r.get("source") != "/(.*)"]
    have = {r["source"] for r in rw}
    added = 0
    for src, dest in routes:
        if src not in have:
            rw.append({"source": src, "destination": dest})
            added += 1
    # Evaluated in order - the catch-all must stay last or it swallows every
    # specific rule above it.
    rw.append({"source": "/(.*)", "destination": "/index.html"})
    cfg["rewrites"] = rw
    if not dry:
        with open(VERCEL, "w", encoding="utf-8") as f:
            json.dump(cfg, f, indent=2)
            f.write("\n")
    return added


def patch_sitemap(paths, dry):
    body = open(SITEMAP, encoding="utf-8").read()
    added = 0
    block = ""
    for p in paths:
        if p in body:
            continue
        block += ("  <url><loc>%s%s</loc><changefreq>monthly</changefreq>"
                  "<priority>0.7</priority></url>\n" % (SITE, p))
        added += 1
    if block and not dry:
        body = body.replace("</urlset>", block + "</urlset>")
        open(SITEMAP, "w", encoding="utf-8").write(body)
    return added


