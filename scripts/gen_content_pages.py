#!/usr/bin/env python3
"""
Prerender the site's explanatory pages as standalone HTML.

WHY
---
17 React routes all serve the same 313-word shell, because content only exists
after JavaScript runs. Google judged the site on that and refused AdSense with
two reasons: "Google-served ads on screens without publisher-content" and "Low
value content". The same emptiness is why those pages do not rank.

The 50 pages under public/predictions/ already solve this - measured at 1,261
words of served HTML against the shell's 313 - so this follows that pattern
rather than inventing one.

CONTENT COMES FROM THE MEASUREMENT, NOT FROM MEMORY
---------------------------------------------------
Accuracy figures are read from the live /backtest-results endpoint at generation
time. The point is that the page and the site can never disagree: if the holdout
is re-run and the number moves, regenerating updates the prose. Hand-typing
"81.5%" into HTML is how a page ends up claiming something the backend stopped
saying months ago - which is exactly what happened to the marketing copy in July.

Run:  python scripts/gen_content_pages.py            (writes + patches vercel.json)
      python scripts/gen_content_pages.py --dry-run  (prints, writes nothing)

Every generated file carries a marker comment; a file WITHOUT it is treated as
hand-written and is never overwritten.
"""

