def patch_vercel(routes, dry):
    with open(VERCEL, encoding="utf-8") as f:
        cfg = json.load(f)
    rw = [r for r in cfg.get("rewrites", []) if r.get("source") != "/(.*)"]
    have = {r["source"] for r in rw}
    added = 0
    for src, dest in routes:
        if src not in have:
            rw.append({"source": src, "destination": dest})
            added += 1
    # The catch-all is evaluated in order and must stay last, or it swallows
    # every specific rule above it.
    rw.append({"source": "/(.*)", "destination": "/index.html"})
    cfg["rewrites"] = rw
    if not dry:
        with open(VERCEL, "w", encoding="utf-8") as f:
            json.dump(cfg, f, indent=2)
            f.write("\n")
    return added


