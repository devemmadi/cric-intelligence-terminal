def checkpoint_rows(chk):
    order = ["ov6", "ov10", "ov12", "ov15", "ov17"]
    rows = ""
    for key in order:
        c = chk.get(key)
        if not c:
            continue
        rows += (f"<tr><td>{c.get('label', key)}</td>"
                 f"<td class='n'>{c.get('accuracy')}%</td>"
                 f"<td class='n'>{c.get('count', 0):,}</td></tr>\n")
    return rows


def calibration_rows(cal):
    rows = ""
    for r in cal:
        mid = (r["lo"] + r["hi"]) / 2
        gap = abs(r["actual_win_rate"] - mid)
        rows += (f"<tr><td>{r['bucket']}</td>"
                 f"<td class='n'>{r['n']:,}</td>"
                 f"<td class='n'>{r['actual_win_rate']}%</td>"
                 f"<td class='n'>{gap:.1f}</td></tr>\n")
    return rows


