# ── the numbers ───────────────────────────────────────────────────────────────

def fetch_accuracy():
    """Read the published holdout result. Fail loudly rather than invent figures."""
    with urllib.request.urlopen(f"{API}/backtest-results", timeout=30) as r:
        data = json.loads(r.read().decode("utf-8"))
    wp = data.get("win_probability") or {}
    total = wp.get("total_predictions") or 0
    if total < 100:
        raise SystemExit(
            f"Refusing to generate: /backtest-results reports {total} predictions. "
            "Publishing an accuracy page from an empty run is how the site ended up "
            "claiming 0.0% for three days in August."
        )
    return {
        "overall": wp.get("overall_accuracy"),
        "predictions": total,
        "matches": data.get("matches_tested"),
        "checkpoints": wp.get("by_checkpoint") or {},
        "calibration": wp.get("calibration") or [],
        "method": data.get("method") or {},
    }


